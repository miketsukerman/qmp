"""One product version (ADR-011): the generator's version is the runtime header's."""

from __future__ import annotations

import re
from pathlib import Path

from protoc_gen_qmp import __version__
from protoc_gen_qmp.emit import runtime_guard

from .conftest import GenResult

VERSION_HEADER = Path(__file__).resolve().parents[2] / "include" / "qmp" / "qmp_version.h"


def _header_version() -> str:
    text = VERSION_HEADER.read_text()
    parts = []
    for part in ("MAJOR", "MINOR", "PATCH"):
        m = re.search(rf"^#define QMP_VERSION_{part} (\d+)$", text, re.MULTILINE)
        assert m, f"QMP_VERSION_{part} missing from {VERSION_HEADER}"
        parts.append(m.group(1))
    return ".".join(parts)


def test_generator_version_is_the_runtime_version() -> None:
    assert __version__ == _header_version()


def test_runtime_guard_before_and_after_1_0() -> None:
    # 0.x: a minor bump may break, so generated code is pinned to its minor.
    assert runtime_guard("0.3.0") == "QMP_VERSION_MAJOR != 0 || QMP_VERSION_MINOR != 3"
    assert runtime_guard("0.3.7") == runtime_guard("0.3.0")
    # >= 1.0: additive minors, so an equal or newer runtime minor is fine.
    assert runtime_guard("1.2.0") == "QMP_VERSION_MAJOR != 1 || QMP_VERSION_MINOR < 2"


def test_generated_header_carries_the_guard(joint: GenResult) -> None:
    h = joint.files["joint.qmp.h"]
    assert f"#if !defined(QMP_VERSION_MAJOR) || {runtime_guard(__version__)}" in h
    assert f'#error "generated by protoc-gen-qmp {__version__}' in h
    assert h.index("#include <qmp/qmp.h>") < h.index("#error")
